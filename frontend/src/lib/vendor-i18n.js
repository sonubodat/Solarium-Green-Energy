export function isSupportedLanguage(code) {
  return LANGUAGES.some((language) => language.code === code);
}

// Falls back to English, then to the key itself, so a missing string never renders blank.
export function translate(language, key, params) {
  const text = TRANSLATIONS[language]?.[key] ?? TRANSLATIONS[DEFAULT_LANGUAGE][key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function translateStatus(language, status) {
  const key = String(status || '').trim().toLowerCase().replace(/[_\s]+/g, ' ');
  return STATUSES[language]?.[key] ?? status;
}

// localStorage can throw or be absent (private mode, blocked site data): the portal then just starts in English.
function browserStorage() {
  try {
    return window.localStorage;
  } catch (error) {
    return null;
  }
}

export function loadLanguage(storage = browserStorage()) {
  try {
    const saved = storage?.getItem(LANGUAGE_STORAGE_KEY);
    return isSupportedLanguage(saved) ? saved : DEFAULT_LANGUAGE;
  } catch (error) {
    return DEFAULT_LANGUAGE;
  }
}

export function saveLanguage(code, storage = browserStorage()) {
  try {
    storage?.setItem(LANGUAGE_STORAGE_KEY, code);
  } catch (error) {
    // not remembered, still applied for this visit
  }
}
